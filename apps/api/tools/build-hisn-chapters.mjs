// Generates src/lib/hisn-chapters.ts: which app chapter each Hisn al-Muslim reading belongs to.
//
//   node tools/build-hisn-chapters.mjs
//
// A dua's link is an app page, /hisn/chapter<n>, and the app defines its chapters: each entry in
// pwa-website/data/duas.json is one of the book's 132 chapters, and its parts are that chapter's
// readings in book order. Reading N is therefore part of whichever chapter's parts cover position N.
// Checked on 2026-09-24 against the test database's record_placements: all 268 agree. Production
// has no placements, which is why the API cannot rely on them alone.
//
// test/dua-canonical-url.test.ts fails if this file and duas.json drift apart.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

export function chaptersByReading(entries) {
  const chapters = [];
  for (const entry of [...entries].sort((a, b) => a.sequence - b.sequence)) {
    for (let part = 0; part < entry.parts.length; part += 1) chapters.push(entry.sequence);
  }
  return chapters;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const { entries } = JSON.parse(readFileSync(resolve(here, '../../../pwa-website/data/duas.json'), 'utf8'));
  const chapters = chaptersByReading(entries);
  const rows = [];
  for (let index = 0; index < chapters.length; index += 20) rows.push(`  ${chapters.slice(index, index + 20).join(', ')},`);
  writeFileSync(resolve(here, '../src/lib/hisn-chapters.ts'), `// Generated by tools/build-hisn-chapters.mjs from pwa-website/data/duas.json -- do not edit by hand.
//
// HISN_CHAPTER_BY_READING[n - 1] is the app chapter (/hisn/chapter<c>) that holds Hisn al-Muslim
// reading n. See the generator for why this exists.
export const HISN_CHAPTER_BY_READING: readonly number[] = [
${rows.join('\n')}
];

export function hisnChapterForReading(reading: number): number | undefined {
  return HISN_CHAPTER_BY_READING[reading - 1];
}
`);
  console.log(`hisn-chapters.ts: ${chapters.length} readings across ${new Set(chapters).size} chapters`);
}
