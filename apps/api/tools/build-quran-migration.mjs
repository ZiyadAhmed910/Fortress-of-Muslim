// Generates the Quran data migration from the copy the PWA already ships, so the two can never
// disagree about what verse 2:255 says. Run from the repository root:
//
//   node apps/api/tools/build-quran-migration.mjs
//
// Writes apps/api/migrations/0025_quran_ayahs.sql. Re-running it is idempotent: the same input
// produces byte-identical output, so it shows up as no diff unless the data actually changed.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const repositoryRoot = new URL('../../../', import.meta.url);
const quranData = new URL('pwa-website/data/quran/', repositoryRoot);
const output = new URL('apps/api/migrations/0025_quran_ayahs.sql', repositoryRoot);

const readJson = (name) => JSON.parse(readFileSync(new URL(name, quranData), 'utf8'));
const sqlText = (value) => `'${String(value).replace(/'/g, "''")}'`;

const index = readJson('index.json');
const rows = [];
for (const surah of index.surahs) {
  const payload = readJson(`surah-${surah.number}.json`);
  if (payload.ayahs.length !== surah.ayahCount) {
    throw new Error(`Surah ${surah.number}: index says ${surah.ayahCount} ayahs, file has ${payload.ayahs.length}.`);
  }
  for (const ayah of payload.ayahs) {
    if (!ayah.en?.trim()) throw new Error(`Surah ${surah.number} ayah ${ayah.n} has no translation to search.`);
    rows.push({
      surah: surah.number,
      ayah: ayah.n,
      nameSimple: surah.nameSimple,
      nameEnglish: surah.nameEnglish,
      place: surah.revelationPlace,
      // Only the translation is stored, and only to search over -- see the licensing note in 0024.
      translation: ayah.en.trim(),
    });
  }
}
if (rows.length !== index.totalAyahs) {
  throw new Error(`Expected ${index.totalAyahs} ayahs, collected ${rows.length}.`);
}

const lines = [
  '-- Generated by apps/api/tools/build-quran-migration.mjs -- do not edit by hand.',
  '-- Source: pwa-website/data/quran, the same files the PWA reads, so a verse cannot differ',
  '-- between what search matches and what the reader is shown.',
  `-- ${rows.length} ayahs across ${index.surahs.length} surahs.`,
  '--',
  '-- The translation is here to be searched, never to be served: the Saheeh International text is',
  '-- not redistributable, and the API returns surah and ayah numbers only. See 0024.',
  '',
];

// One statement per surah rather than 6,236 separate INSERTs, or one statement of 6,236 rows:
// the first is slow to apply and the second risks the statement size limit.
for (const surah of index.surahs) {
  const surahRows = rows.filter((row) => row.surah === surah.number);
  lines.push(`INSERT INTO quran_ayahs (surah, ayah, surah_name_simple, surah_name_english, revelation_place, translation) VALUES`);
  lines.push(surahRows.map((row) => `  (${row.surah}, ${row.ayah}, ${sqlText(row.nameSimple)}, ${sqlText(row.nameEnglish)}, ${sqlText(row.place)}, ${sqlText(row.translation)})`).join(',\n') + ';');
  lines.push('');
}

lines.push('-- The lexical index, carrying the surah name so "al-baqarah 255" finds its way home.');
lines.push('INSERT INTO quran_search_fts (surah, ayah, surah_name, translation)');
lines.push("SELECT surah, ayah, surah_name_simple || ' ' || surah_name_english, translation FROM quran_ayahs;");
lines.push('');
lines.push('-- Queue the embedding pass. The cron walks this the same way it walks the record index.');
lines.push("INSERT INTO quran_index_state (namespace, expected_count, indexed_count, status, updated_at)");
lines.push(`VALUES ('quran.saheeh.v1', ${rows.length}, 0, 'pending', CURRENT_TIMESTAMP);`);
lines.push('');

writeFileSync(output, lines.join('\n'));
const bytes = readFileSync(output).length;
console.log(`Wrote ${fileURLToPath(output)} -- ${rows.length} ayahs, ${(bytes / 1048576).toFixed(2)}MB.`);
