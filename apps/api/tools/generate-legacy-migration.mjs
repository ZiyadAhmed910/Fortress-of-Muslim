import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const sourceUrl = new URL('../../../pwa-website/data/duas.json', import.meta.url);
const outputUrl = new URL('../migrations/0002_import_legacy_dataset.sql', import.meta.url);
const sourceText = await readFile(sourceUrl, 'utf8');
const source = JSON.parse(sourceText);

validateSource(source);

const datasetId = 'dataset.hisn.legacy.2026-07-11-v2';
const sourceVersion = '2026-07-11-v2';
const importedAt = '2026-07-18T00:00:00.000Z';
const contentHash = createHash('sha256').update(sourceText).digest('hex');
const lines = [
  '-- Generated by tools/generate-legacy-migration.mjs. Do not edit manually.',
  `-- Source SHA-256: ${contentHash}`,
  'PRAGMA foreign_keys = ON;',
  `DELETE FROM dataset_versions WHERE id = ${sql(datasetId)};`,
  `INSERT INTO dataset_versions (id, source_name, source_version, generated_from, publication_status, verification_status, record_count, content_hash, imported_at) VALUES (${[
    datasetId,
    'Hisn al-Muslim legacy import',
    sourceVersion,
    source.generatedFrom,
    'active',
    'pending',
    source.entries.length,
    contentHash,
    importedAt,
  ].map(sql).join(', ')});`,
];

for (const entry of [...source.entries].sort((left, right) => left.sequence - right.sequence)) {
  const recordId = canonicalDuaId(entry.sequence);
  lines.push(
    `INSERT INTO content_records (id, dataset_id, content_type, legacy_id, sequence, title, verification_status, created_at, updated_at) VALUES (${[
      recordId,
      datasetId,
      'dua',
      entry.uid,
      entry.sequence,
      entry.title,
      'pending',
      importedAt,
      importedAt,
    ].map(sql).join(', ')});`,
  );

  entry.parts.forEach((part, partIndex) => {
    const partId = `${recordId}.part.${pad(partIndex + 1)}`;
    lines.push(
      `INSERT INTO content_parts (id, record_id, position) VALUES (${sql(partId)}, ${sql(recordId)}, ${partIndex + 1});`,
    );

    part.forEach((segment, segmentIndex) => {
      const segmentId = `${partId}.segment.${pad(segmentIndex + 1)}`;
      const locale = segmentLocale(segment.kind);
      lines.push(
        `INSERT INTO content_segments (id, part_id, position, kind, language_code, script_code, text) VALUES (${[
          segmentId,
          partId,
          segmentIndex + 1,
          segment.kind,
          locale.language,
          locale.script,
          segment.text,
        ].map(sql).join(', ')});`,
      );
    });
  });
}

await writeFile(outputUrl, `${lines.join('\n')}\n`, 'utf8');
console.log(`Generated ${fileURLToPath(outputUrl)} with ${source.entries.length} records (${contentHash}).`);

function validateSource(data) {
  if (!data || !Array.isArray(data.entries) || data.entries.length !== data.count) {
    throw new Error('Legacy source count does not match its entries.');
  }

  const sequences = new Set();
  for (const entry of data.entries) {
    if (!entry.uid || !entry.title || !Number.isInteger(entry.sequence) || !Array.isArray(entry.parts)) {
      throw new Error(`Invalid legacy entry: ${JSON.stringify(entry).slice(0, 100)}`);
    }
    if (sequences.has(entry.sequence)) throw new Error(`Duplicate sequence: ${entry.sequence}`);
    sequences.add(entry.sequence);

    for (const part of entry.parts) {
      if (!Array.isArray(part)) throw new Error(`Invalid part in ${entry.uid}`);
      for (const segment of part) {
        if (!['arabic', 'transliteration', 'translation', 'comment'].includes(segment.kind)) {
          throw new Error(`Invalid segment kind in ${entry.uid}: ${segment.kind}`);
        }
        if (typeof segment.text !== 'string') throw new Error(`Invalid segment text in ${entry.uid}`);
      }
    }
  }
}

function canonicalDuaId(sequence) {
  return `dua.hisn.${pad(sequence)}`;
}

function pad(value) {
  return String(value).padStart(3, '0');
}

function segmentLocale(kind) {
  if (kind === 'arabic') return { language: 'ar', script: 'Arab' };
  if (kind === 'transliteration') return { language: 'ar-Latn', script: 'Latn' };
  return { language: 'en', script: 'Latn' };
}

function sql(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return String(value);
  return `'${String(value).replaceAll("'", "''")}'`;
}
