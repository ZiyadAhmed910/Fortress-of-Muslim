// Adds the Arabic of every ayah to quran_ayahs, generated from the copy the PWA ships.
//
// The translation was stored alone because search only needs words to match on. Then verses became
// citable sources in Ask, the model was handed a context containing the English only -- and it wrote
// the Arabic anyway, from its own memory, trailing off in an ellipsis. Quranic text recalled by a
// language model is exactly what this platform exists not to publish, so the Arabic is stored and
// quoted from the source.
//
// Run from the repository root:
//   node apps/api/tools/build-quran-arabic-migration.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const repositoryRoot = new URL('../../../', import.meta.url);
const quranData = new URL('pwa-website/data/quran/', repositoryRoot);
const output = new URL('apps/api/migrations/0026_quran_arabic.sql', repositoryRoot);

const readJson = (name) => JSON.parse(readFileSync(new URL(name, quranData), 'utf8'));
const sqlText = (value) => `'${String(value).replace(/'/g, "''")}'`;

const index = readJson('index.json');
const rows = [];
for (const surah of index.surahs) {
  const payload = readJson(`surah-${surah.number}.json`);
  for (const ayah of payload.ayahs) {
    // `ar` is the plain Arabic; `tj` carries tajweed markup, which is presentation for the reader
    // and noise in a model's context.
    if (!ayah.ar?.trim()) throw new Error(`Surah ${surah.number} ayah ${ayah.n} has no Arabic.`);
    rows.push({ surah: surah.number, ayah: ayah.n, arabic: ayah.ar.trim() });
  }
}
if (rows.length !== index.totalAyahs) throw new Error(`Expected ${index.totalAyahs} ayahs, collected ${rows.length}.`);

const lines = [
  '-- Generated by apps/api/tools/build-quran-arabic-migration.mjs -- do not edit by hand.',
  '--',
  '-- Ask cites verses, and until now its context for one carried the English translation alone. The',
  '-- model filled in the Arabic from memory and truncated it mid-verse. Quranic text recalled by a',
  '-- language model is the one thing this platform must never put in front of a reader, so the',
  '-- Arabic is stored here and quoted from the source.',
  '--',
  '-- Search still runs on the translation: this column is never matched against, only returned.',
  `-- ${rows.length} ayahs, plain Arabic (Tanzil, CC BY 3.0) without tajweed markup.`,
  '',
  "ALTER TABLE quran_ayahs ADD COLUMN arabic TEXT NOT NULL DEFAULT '';",
  '',
];

// One statement per surah: 6,236 single-row updates are slow to apply, and one statement of 6,236
// is a statement-size gamble.
for (const surah of index.surahs) {
  const surahRows = rows.filter((row) => row.surah === surah.number);
  lines.push(`UPDATE quran_ayahs SET arabic = CASE ayah`);
  lines.push(surahRows.map((row) => `  WHEN ${row.ayah} THEN ${sqlText(row.arabic)}`).join('\n'));
  lines.push(`  ELSE arabic END WHERE surah = ${surah.number};`);
  lines.push('');
}

writeFileSync(output, lines.join('\n'));
console.log(`Wrote ${fileURLToPath(output)} -- ${rows.length} ayahs, ${(readFileSync(output).length / 1048576).toFixed(2)}MB.`);
